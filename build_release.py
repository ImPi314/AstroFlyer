"""
AstroFlyer HEO - Release Build & Installer Packaging Pipeline
Department of Aerospace Engineering, ACS College of Engineering

Orchestrates:
0. Preflight: offline data present (astroflyer/resources/manifest.json)
1. PyInstaller standalone onedir compilation -> dist/AstroFlyer_HEO/AstroFlyer.exe
2. Inno Setup installer compilation -> dist_installer/AstroFlyer_HEO_v<version>_Setup.exe
3. Integrity and checksum verification
4. With --publish: GitHub release v<version> carrying the installer (GitHub CLI, logged in)

The version is astroflyer/__init__.py's __version__; raise it there before building a release.

    python build_release.py                      # build only
    python build_release.py --publish            # build, then publish (notes generated by GitHub)
    python build_release.py --publish --notes release_notes.md
"""

import argparse
import os
import re
import shutil
import sys
import subprocess
import hashlib
import time

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
ISCC_CANDIDATE_PATHS = [
    os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs", "Inno Setup 6", "ISCC.exe"),
    r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe",
    r"C:\Program Files\Inno Setup 6\ISCC.exe",
]
ISCC_PATH = next((p for p in ISCC_CANDIDATE_PATHS if os.path.exists(p)), None)


def compute_sha256(filepath):
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


GH_CANDIDATE_PATHS = [r"C:\Program Files\GitHub CLI\gh.exe"]


def app_version():
    """The app's version, read from astroflyer/__init__.py (the only place it is written)."""
    with open(os.path.join(PROJECT_ROOT, "astroflyer", "__init__.py"), encoding="utf-8") as f:
        match = re.search(r'^__version__\s*=\s*"([^"]+)"', f.read(), re.MULTILINE)
    if not match:
        raise RuntimeError("astroflyer/__init__.py has no __version__")
    return match.group(1)


def installer_name(version):
    return f"AstroFlyer_HEO_v{version}_Setup.exe"


def iscc_command(iss_path, version):
    return [ISCC_PATH, "/Qp", f"/DMyAppVersion={version}", iss_path]


def _git(*args):
    return subprocess.run(["git", *args], cwd=PROJECT_ROOT, capture_output=True, text=True,
                          check=True).stdout.strip()


def release_blockers(version, git=_git):
    """Why release v<version> cannot be published from this checkout now (empty when it can)."""
    blockers = []
    if git("status", "--porcelain"):
        blockers.append("there are uncommitted changes; commit them first")
    if git("rev-parse", "HEAD") != git("rev-parse", "origin/main"):
        blockers.append("this commit is not origin/main; push main (or check it out) first")
    tags = {line.split()[-1] for line in git("ls-remote", "--tags", "origin").splitlines() if line.strip()}
    if f"refs/tags/v{version}" in tags:
        blockers.append(f"v{version} is already released; raise __version__ in astroflyer/__init__.py")
    return blockers


def publish(version, installer_path, notes_path=None):
    """Creates GitHub release v<version> at the current commit, with the installer attached."""
    gh = shutil.which("gh") or next((p for p in GH_CANDIDATE_PATHS if os.path.exists(p)), None)
    if gh is None:
        print("[ERROR] GitHub CLI (gh) not found; install it and run 'gh auth login'.")
        sys.exit(1)
    cmd = [gh, "release", "create", f"v{version}", installer_path, "--target", _git("rev-parse", "HEAD"),
           "--title", f"AstroFlyer HEO {version}"]
    cmd += ["--notes-file", notes_path] if notes_path else ["--generate-notes"]
    if subprocess.run(cmd, cwd=PROJECT_ROOT).returncode != 0:
        print("\n[ERROR] Publishing the release failed; the installer is built, rerun with --publish.")
        sys.exit(1)


def python_supported(version_info):
    """The app needs 3.12+ (typing.override); 3.14 is verified on Windows with every dependency."""
    return tuple(version_info[:2]) >= (3, 12)


def preflight():
    """Stops the build when a required runtime file is missing; warns about optional ones."""
    ok = True
    if not python_supported(sys.version_info):
        print(f"[ERROR] Python {sys.version_info.major}.{sys.version_info.minor} is too old; build with Python 3.12 or newer.")
        ok = False
    sys.path.insert(0, os.path.join(PROJECT_ROOT, "astroflyer"))
    import offline_data
    for item in offline_data.data_status():
        if item["present"]:
            print(f"      [+] {item['file']} (valid until {item['valid_until']})")
        elif item["required"]:
            print(f"[ERROR] Required offline data missing: astroflyer/resources/{item['file']}")
            ok = False
        else:
            print(f"      [-] Optional {item['file']} not bundled (python tools/fetch_offline_data.py)")
    redist = os.path.join(PROJECT_ROOT, "installer", "redist", "MicrosoftEdgeWebView2RuntimeInstallerX64.exe")
    if not os.path.exists(redist):
        print("      [-] No offline WebView2 installer in installer/redist/; setup will ask users without WebView2 to install it.")
    return ok


def main():
    parser = argparse.ArgumentParser(description="Build the AstroFlyer HEO app and installer")
    parser.add_argument("--publish", action="store_true", help="publish GitHub release v<version> after building")
    parser.add_argument("--notes", help="release notes file (default: notes generated by GitHub)")
    args = parser.parse_args()
    version = app_version()
    if args.publish:
        _git("fetch", "--quiet", "origin")
        blockers = release_blockers(version)
        if blockers:
            print("[ERROR] Cannot publish v" + version + ": " + "; ".join(blockers))
            sys.exit(1)

    print("=" * 80)
    print(f"      ASTROFLYER HEO {version} - STANDALONE EXE & INSTALLER BUILD PIPELINE")
    print("      Department of Aerospace Engineering | ACS College of Engineering")
    print("=" * 80)
    start_time = time.time()

    print("\n[*] [0/2] Preflight checks...")
    if not preflight():
        sys.exit(1)

    # Step 1: Run PyInstaller to build standalone desktop application
    print("\n[*] [1/2] Building Standalone Windows Desktop Application with PyInstaller...")
    spec_path = os.path.join(PROJECT_ROOT, "AstroFlyer.spec")
    pyinstaller_cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", spec_path]
    res = subprocess.run(pyinstaller_cmd, cwd=PROJECT_ROOT)
    if res.returncode != 0:
        print("\n[ERROR] PyInstaller build failed!")
        sys.exit(1)

    exe_path = os.path.join(PROJECT_ROOT, "dist", "AstroFlyer_HEO", "AstroFlyer.exe")
    if not os.path.exists(exe_path):
        print(f"\n[ERROR] Output executable not found at: {exe_path}")
        sys.exit(1)

    exe_size_mb = os.path.getsize(exe_path) / (1024 * 1024)
    print(f"      [+] Standalone Executable generated successfully: {exe_path} ({exe_size_mb:.2f} MB)")

    # Step 2: Run Inno Setup Compiler to create the installer
    print("\n[*] [2/2] Compiling Inno Setup Windows Installer Package...")
    if not ISCC_PATH or not os.path.exists(ISCC_PATH):
        print(f"[!] Warning: ISCC.exe not found at standard locations. Checked: {ISCC_CANDIDATE_PATHS}")
        print("[!] Standalone executable in dist/AstroFlyer_HEO is ready, but installer compilation skipped.")
        return

    iss_path = os.path.join(PROJECT_ROOT, "installer", "AstroFlyer_Installer.iss")
    res_iscc = subprocess.run(iscc_command(iss_path, version), cwd=os.path.join(PROJECT_ROOT, "installer"))
    if res_iscc.returncode != 0:
        print("\n[ERROR] Inno Setup compilation failed!")
        sys.exit(1)

    installer_path = os.path.join(PROJECT_ROOT, "dist_installer", installer_name(version))
    if not os.path.exists(installer_path):
        print(f"\n[ERROR] Installer output not found at: {installer_path}")
        sys.exit(1)

    inst_size_mb = os.path.getsize(installer_path) / (1024 * 1024)
    inst_hash = compute_sha256(installer_path)

    elapsed = time.time() - start_time
    print("\n" + "=" * 80)
    print("      BUILD & PACKAGING COMPLETE - ALL TARGETS READY")
    print("=" * 80)
    print(f"  [+] Standalone Executable: {exe_path}")
    print(f"  [+] Windows Installer    : {installer_path}")
    print(f"  [+] Installer Size       : {inst_size_mb:.2f} MB")
    print(f"  [+] SHA-256 Checksum     : {inst_hash}")
    print(f"  [+] Total Build Time     : {elapsed:.1f} seconds")
    print("=" * 80)

    if args.publish:
        print(f"\n[*] Publishing GitHub release v{version}...")
        publish(version, installer_path, args.notes)


if __name__ == "__main__":
    main()
